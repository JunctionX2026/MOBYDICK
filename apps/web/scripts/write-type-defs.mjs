import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Workers cannot read files at runtime, so the SDL that relay-compiler reads is
 * mirrored into a module the server bundle can import. schema.graphql stays the
 * only place the schema is written by hand.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sdl = readFileSync(join(root, "schema.graphql"), "utf8").trim();
const target = join(root, "src/__generated__/type-defs.ts");

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// @generated by scripts/write-type-defs.mjs from schema.graphql. Do not edit.\nexport const typeDefs = ${JSON.stringify(sdl)};\n`,
);

console.log(`wrote ${target}`);
